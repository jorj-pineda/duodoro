import { randomUUID } from 'node:crypto';
import AxeBuilder from '@axe-core/playwright';
import { test, expect, AUTH_STORAGE_KEY, requireSuccess } from './duoFixture';
import { onboard } from './onboard';

test('a private goal becomes a reviewed room intention, and wrap-up keeps drafts and private progress safe', async ({ duo }) => {
  test.setTimeout(180_000);
  const { a,b,admin,roomCodes } = duo; const suffix = randomUUID().slice(0,8);
  await a.page.goto('/'); await onboard(a.page,'Goal Alpha',`ga_${suffix}`);
  await a.page.getByRole('textbox',{ name: 'New goal' }).fill('Private chapter');
  await a.page.getByRole('button',{ name: 'Add goal', exact: true }).click();
  await a.page.getByRole('button',{ name: 'Focus on Private chapter', exact: true }).click();
  const room = await a.page.evaluate(() => localStorage.getItem('duodoro:session'));
  await expect(a.page.getByRole('textbox',{ name: 'Your session intention' })).toHaveValue('Private chapter');
  const actualRoom = room || await a.page.evaluate(() => localStorage.getItem('duodoro:session'));
  if (!actualRoom) throw new Error('Missing goal room'); roomCodes.add(actualRoom);
  await expect(a.page.getByRole('button',{ name: 'Start solo', exact: true })).toBeDisabled();
  await a.page.getByRole('button',{ name: 'Done for today?', exact: true }).click();
  let wrap = a.page.getByRole('dialog',{ name: 'Done for today?', exact: true });
  await expect(wrap.getByRole('button',{ name: 'Finish and leave room' })).toBeDisabled();
  await wrap.getByRole('button',{ name: 'Return to room' }).click();
  await expect(a.page.getByRole('textbox',{ name: 'Your session intention' })).toHaveValue('Private chapter');
  await a.page.getByRole('button',{ name: 'Copy invite link' }).click();
  await expect(a.page.getByText('Invite link copied!')).toBeVisible();
  const invite = await a.page.evaluate(() => navigator.clipboard.readText());
  await b.page.goto(invite); await expect(b.page.getByRole('heading',{ name: 'Focus together' })).toBeVisible();
  await b.page.evaluate(({key,session}) => localStorage.setItem(key,JSON.stringify(session)),{key:AUTH_STORAGE_KEY,session:b.session});
  await b.page.reload(); await onboard(b.page,'Goal Beta',`gb_${suffix}`);
  await expect(b.page.getByText('Private chapter',{ exact: true })).toHaveCount(0);
  await a.page.getByRole('textbox',{ name: 'Your session intention' }).fill('Reviewed chapter');
  await a.page.getByRole('button',{ name: 'Save intention', exact: true }).click();
  await expect(b.page.getByText('Goal Alpha: Reviewed chapter',{ exact: true })).toBeVisible();
  const goal = await a.client.from('tasks').select('content,is_done,is_shared,room_code').eq('owner_id',a.id).single();
  requireSuccess(goal.error,'Read source goal'); expect(goal.data).toMatchObject({ content:'Private chapter',is_done:false,is_shared:false,room_code:null });
  const bPrompt = b.page.getByRole('region',{ name: 'Session intentions', exact: true });
  await bPrompt.getByRole('button',{ name: 'Add intention' }).click();
  await bPrompt.getByRole('textbox').fill('Partner plan'); await bPrompt.getByRole('textbox').press('Enter');
  const soloRoom = randomUUID(); roomCodes.add(soloRoom);
  requireSuccess((await admin.rpc('record_focus_session',{ p_recording_key:randomUUID(),p_room_code:soloRoom,p_world:'forest',p_focus_duration:900,p_break_duration:60,p_actual_focus:900,p_completed:true,p_started_at:new Date(Date.now()-900000).toISOString(),p_user_ids:[b.id] })).error,'Seed partner-only focus');
  await a.page.getByRole('button',{ name: 'Flowmodoro', exact: true }).click();
  await a.page.getByRole('button',{ name: 'Start session', exact: true }).click();
  await expect.poll(() => a.page.title()).toMatch(/0:0[1-9] · Flow/);
  await a.page.getByRole('button',{ name: 'Take break', exact: true }).click();
  await expect(a.page.getByRole('region',{ name:'Round recap',exact:true })).toContainText('Round saved');
  await a.page.getByRole('button',{ name: 'Done for today?', exact: true }).click();
  wrap = a.page.getByRole('dialog',{ name: 'Done for today?', exact: true });
  await expect(wrap.getByText('1',{ exact: true })).toBeVisible();
  await expect(wrap.getByText('Reviewed chapter',{ exact: true })).toBeVisible();
  await expect(wrap.getByText('Partner plan',{ exact: true })).toHaveCount(0);
  await expect(wrap.locator('dd').filter({ hasText:/^\d+s$/ })).toBeVisible();
  await a.page.route('**/rest/v1/rpc/get_daily_focus', route => route.fulfill({status:503,contentType:'application/json',body:'{"message":"Unavailable"}'}));
  await a.page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(wrap.getByRole('alert')).toContainText('unavailable');
  await a.page.unroute('**/rest/v1/rpc/get_daily_focus');
  await wrap.getByRole('button',{ name: 'Retry today’s focus' }).click();
  await expect(wrap.getByRole('alert')).toHaveCount(0);
  expect((await new AxeBuilder({page:a.page}).include('[aria-labelledby="wrap-up-title"]').withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze()).violations).toEqual([]);
  for(const [name,width,height] of [['phone',375,667],['landscape',667,375]] as const){
    await a.page.setViewportSize({width,height}); await wrap.getByRole('button',{name:'Finish and leave room'}).scrollIntoViewIfNeeded();
    await expect(wrap.getByRole('button',{name:'Finish and leave room'})).toBeInViewport();
    expect(await a.page.evaluate(() => document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await a.page.screenshot({path:test.info().outputPath(`wrap-up-${name}.png`)});
  }
  await wrap.getByRole('button',{ name: 'Finish and leave room' }).click();
  await expect(a.page.getByText('Private chapter',{ exact: true })).toBeVisible();
  const retained = await a.client.from('tasks').select('is_done').eq('owner_id',a.id).single();
  requireSuccess(retained.error,'Keep goal incomplete'); expect(retained.data?.is_done).toBe(false);
});
