import { randomUUID } from 'node:crypto';
import AxeBuilder from '@axe-core/playwright';
import { test, expect, AUTH_STORAGE_KEY, requireSuccess } from './duoFixture';
import { onboard } from './onboard';

test('an unfinished intention becomes one private goal across retries and refresh, without changing the next plan', async ({ duo }) => {
  test.setTimeout(180_000);
  const { a, b, roomCodes } = duo;
  const suffix = randomUUID().slice(0,8);
  await a.page.goto('/'); await onboard(a.page, 'Carry Alpha', `ia_${suffix}`);
  await a.page.getByRole('button', { name: 'Focus', exact: true }).click();
  await a.page.getByRole('button', { name: 'Copy invite link' }).click();
  await expect(a.page.getByText('Invite link copied!')).toBeVisible();
  const invite = await a.page.evaluate(() => navigator.clipboard.readText());
  const room = await a.page.evaluate(() => localStorage.getItem('duodoro:session'));
  if (!room) throw new Error('Missing intention room'); roomCodes.add(room);
  await b.page.goto(invite);
  await expect(b.page.getByRole('heading', { name: 'Focus together' })).toBeVisible();
  await b.page.evaluate(({ key, session }) => localStorage.setItem(key, JSON.stringify(session)), { key: AUTH_STORAGE_KEY, session: b.session });
  await b.page.reload(); await onboard(b.page, 'Carry Beta', `ib_${suffix}`);
  await expect(a.page.getByRole('button', { name: 'Start session', exact: true })).toBeVisible();
  const text = 'Finish the private follow-up';
  const prompt = a.page.getByRole('region', { name: 'Session intentions', exact: true });
  await prompt.getByRole('button', { name: 'Add intention' }).click();
  await prompt.getByRole('textbox').fill(text); await prompt.getByRole('textbox').press('Enter');
  await expect(prompt.getByText(`You: ${text}`)).toBeVisible();
  await a.page.getByRole('button', { name: 'Flowmodoro', exact: true }).click();
  await a.page.getByRole('button', { name: 'Start session', exact: true }).click();
  await expect.poll(() => a.page.title()).toMatch(/0:0[1-9] · Flow/);
  await a.page.getByRole('button', { name: 'Take break', exact: true }).click();
  const recap = a.page.getByRole('region', { name: 'Round intentions', exact: true });
  await expect(recap.getByRole('button', { name: 'Save as personal goal' })).toBeVisible();
  await expect(b.page.getByRole('button', { name: 'Save as personal goal' })).toHaveCount(0);
  expect((await new AxeBuilder({ page: a.page }).include('[aria-label="Carry-forward personal goal"]').withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze()).violations).toEqual([]);
  await a.page.getByRole('button', { name: 'Switch to dark mode' }).click();
  expect((await new AxeBuilder({ page: a.page }).include('[aria-label="Carry-forward personal goal"]').withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze()).violations).toEqual([]);
  await a.page.getByRole('button', { name: 'Switch to light mode' }).click();
  await recap.getByRole('button', { name: 'Carry into next round' }).click();
  await expect(recap.getByRole('button', { name: 'Carried into next round' })).toBeDisabled();
  // Lose the first response after forwarding the real write to the database.
  let lost = false;
  await a.page.route('**/rest/v1/tasks?*', async route => {
    if (!lost && route.request().method() === 'POST') {
      lost = true;
      await route.fetch();
      await route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"Unconfirmed"}' });
    } else await route.continue();
  });
  await recap.getByRole('button', { name: 'Save as personal goal' }).click();
  await expect(recap.getByRole('alert')).toContainText("Couldn't confirm");
  await a.page.unroute('**/rest/v1/tasks?*');
  await recap.getByRole('button', { name: 'Save as personal goal' }).click();
  await expect(recap.getByRole('button', { name: 'Saved as personal goal' })).toBeDisabled();
  await expect(recap.getByRole('status')).toContainText('still unfinished');
  const own = await a.client.from('tasks').select('id,content,is_done,is_shared,room_code').eq('owner_id',a.id).eq('content',text);
  requireSuccess(own.error,'Read carried goal'); expect(own.data).toHaveLength(1);
  expect(own.data![0]).toMatchObject({ content: text, is_done: false, is_shared: false, room_code: null });
  const goalId = own.data![0].id;
  const partner = await b.client.from('tasks').select('id').eq('id',goalId);
  requireSuccess(partner.error,'Read partner privacy'); expect(partner.data).toEqual([]);
  const forbidden = await b.client.from('tasks').update({ content: 'Changed by partner' }).eq('id',goalId).select('id');
  requireSuccess(forbidden.error,'Refuse partner edit'); expect(forbidden.data).toEqual([]);
  requireSuccess((await a.client.from('tasks').update({ content: 'Edited personal follow-up', is_done: true }).eq('id',goalId)).error,'Edit carried goal');
  await a.page.reload();
  await recap.getByRole('button', { name: 'Save as personal goal' }).click();
  await expect(recap.getByRole('button', { name: 'Saved as personal goal' })).toBeDisabled();
  const retained = await a.client.from('tasks').select('id,content,is_done').eq('id',goalId).single();
  requireSuccess(retained.error,'Read retained edit'); expect(retained.data).toMatchObject({ content: 'Edited personal follow-up', is_done: true });
  await a.page.setViewportSize({ width: 375, height: 667 });
  await recap.getByRole('region', { name: 'Carry-forward personal goal' }).scrollIntoViewIfNeeded();
  await expect(recap.getByRole('button', { name: 'Saved as personal goal' })).toBeInViewport();
  await expect(recap.getByRole('status')).toBeInViewport();
  expect(await a.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await a.page.screenshot({ path: test.info().outputPath('intention-goal-phone.png') });
  await a.page.setViewportSize({ width: 667, height: 375 });
  await recap.getByRole('region', { name: 'Carry-forward personal goal' }).scrollIntoViewIfNeeded();
  await expect(recap.getByRole('button', { name: 'Saved as personal goal' })).toBeInViewport();
  await expect(recap.getByRole('status')).toBeInViewport();
  expect(await a.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await a.page.screenshot({ path: test.info().outputPath('intention-goal-landscape.png') });
  await a.page.getByRole('button', { name: /Leave room/ }).click();
  await expect(a.page.getByText('Edited personal follow-up', { exact: true })).toBeVisible();
});
