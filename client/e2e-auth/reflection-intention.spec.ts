import { randomUUID } from "node:crypto";
import { test,expect,requireSuccess,AUTH_STORAGE_KEY } from "./duoFixture";
import { onboard } from "./onboard";

test("a saved reflection stays private until its reviewed intention is explicitly shared", async ({ duo }) => {
  const { a,b,admin,roomCodes } = duo;
  await a.page.goto("/"); await onboard(a.page,"Draft Alpha",`rda_${randomUUID().slice(0,8)}`);
  await b.page.goto("/"); await b.page.evaluate(({ key,session }) => localStorage.setItem(key,JSON.stringify(session)),{ key:AUTH_STORAGE_KEY,session:b.session });
  await b.page.reload(); await onboard(b.page,"Draft Beta",`rdb_${randomUUID().slice(0,8)}`);
  const fixtureRoom = randomUUID(); roomCodes.add(fixtureRoom);
  const recorded = await admin.rpc("record_focus_session",{ p_recording_key:randomUUID(),p_room_code:fixtureRoom,p_world:"forest",p_focus_duration:600,p_break_duration:60,p_actual_focus:600,p_completed:true,p_started_at:new Date(Date.now()-600000).toISOString(),p_user_ids:[a.id,b.id] });
  requireSuccess(recorded.error,"Record reflection-intention fixture");
  const note = "Private reflection that needs review.\n".repeat(6).trim();
  requireSuccess((await a.client.rpc("create_session_reflection",{ p_session_id:recorded.data![0].session_id,p_text:note })).error,"Save private reflection");
  await a.page.getByRole("button",{ name:"Open stats",exact:true }).click();
  const stats = a.page.getByRole("dialog",{ name:"Stats",exact:true });
  await stats.getByRole("tab",{ name:"reflections",exact:true }).click();
  const use = stats.getByRole("button",{ name:"Use for my next focus",exact:true });
  await use.click(); await expect(stats.getByText(/Private draft prepared/)).toBeVisible();
  await use.click(); await expect(stats.getByText(/Nothing was replaced/)).toBeVisible();
  await stats.getByRole("button",{ name:"Close",exact:true }).click();
  await a.page.getByRole("button",{ name:"Focus",exact:true }).click();
  const editor = a.page.getByRole("region",{ name:"Session intentions",exact:true });
  const input = editor.getByRole("textbox",{ name:"Your session intention" });
  await expect(input).toHaveValue(note); await expect(editor.getByRole("button",{ name:"Save intention",exact:true })).toBeDisabled();
  await a.page.getByRole("button",{ name:"Copy invite link",exact:true }).click(); await expect(a.page.getByText("Invite link copied!",{ exact:true })).toBeVisible();
  const invite = await a.page.evaluate(() => navigator.clipboard.readText()); await b.page.goto(invite);
  const room = await a.page.evaluate(() => localStorage.getItem("duodoro:session")); if (!room) throw new Error("Missing draft room"); roomCodes.add(room);
  await expect(b.page.getByRole("button",{ name:"Start session",exact:true })).toBeVisible();
  await expect(b.page.getByText(note,{ exact:true })).toHaveCount(0);
  await expect(a.page.getByRole("button",{ name:"Start session",exact:true })).toBeDisabled();
  await a.page.setViewportSize({ width:390,height:844 }); await input.scrollIntoViewIfNeeded();
  expect(await a.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await a.page.screenshot({ path:test.info().outputPath("private-intention-draft-phone.png") });
  await input.fill("Read one chapter"); await editor.getByRole("button",{ name:"Save intention",exact:true }).click();
  await expect(b.page.getByText("Draft Alpha: Read one chapter",{ exact:true })).toBeVisible();
  await expect(a.page.getByRole("button",{ name:"Start session",exact:true })).toBeEnabled();
  const original = await a.client.from("session_reflections").select("reflection_text").eq("session_id",recorded.data![0].session_id).single();
  requireSuccess(original.error,"Read unchanged reflection"); expect(original.data!.reflection_text).toBe(note);
});
