import { randomUUID } from "node:crypto";
import AxeBuilder from "@axe-core/playwright";
import { test, expect, AUTH_STORAGE_KEY, requireSuccess } from "./duoFixture";
import { onboard } from "./onboard";
import { previousWeek, weekStart } from "../src/lib/weeklyPlan";

test("private weekly review carries selected goals without changing history and reconciles conflicts or lost acknowledgements", async ({ duo }) => {
  test.setTimeout(180_000);
  const { a, b, admin } = duo;
  const suffix = randomUUID().slice(0, 8);
  await a.page.goto("/"); await onboard(a.page, "Review Alpha", `wra_${suffix}`);
  await expect(a.page.getByRole("button", { name: "Focus", exact: true })).toBeVisible();
  await b.page.goto("/");
  await b.page.evaluate(({ key, session }) => localStorage.setItem(key, JSON.stringify(session)), { key: AUTH_STORAGE_KEY, session: b.session });
  await b.page.reload(); await onboard(b.page, "Review Beta", `wrb_${suffix}`);
  await expect(b.page.getByRole("button", { name: "Focus", exact: true })).toBeVisible();
  requireSuccess((await admin.from("friendships").insert({ requester_id: a.id, addressee_id: b.id, status: "accepted" })).error, "Create review fixture friends");
  const created = await a.client.from("tasks").insert(["Old unfinished", "Old finished", "Already planned", "This week only"]
    .map(content => ({ owner_id: a.id, content: `${content} ${suffix}`, is_done: content === "Old finished" }))).select("id,content,is_done");
  requireSuccess(created.error, "Create review goals");
  const goal = (name: string) => created.data!.find(row => row.content.startsWith(name))!;
  const unfinished = goal("Old unfinished"), finished = goal("Old finished"), already = goal("Already planned"), currentOnly = goal("This week only");
  const week = weekStart(await a.page.evaluate(() => {
    const date = new Date(); return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
  }));
  const lastWeek = previousWeek(week);
  const oldIds = [unfinished.id, finished.id, already.id];
  const old = await a.client.rpc("set_weekly_focus_plan", { p_week_start: lastWeek, p_task_ids: oldIds, p_expected_version: null as unknown as number });
  requireSuccess(old.error, "Create prior review plan");
  requireSuccess((await a.client.rpc("set_weekly_focus_plan", { p_week_start: week, p_task_ids: [already.id, currentOnly.id], p_expected_version: null as unknown as number })).error, "Create current review plan");
  const taskSnapshot = await a.client.from("tasks").select("id,content,is_done,room_code,is_shared").order("id");
  requireSuccess(taskSnapshot.error, "Read review source goals");
  await a.page.reload();
  const plan = a.page.getByRole("region", { name: "Private weekly focus plan", exact: true });
  const review = a.page.getByRole("region", { name: "Private weekly plan review", exact: true });
  await expect(plan.getByText("0 of 2 planned goals complete", { exact: true })).toBeVisible();
  await expect(review).toHaveCount(0);
  await plan.getByRole("button", { name: "Review last week", exact: true }).click();
  await expect(review.getByText("Complete now", { exact: true })).toBeVisible();
  await expect(review.getByText("Already in this week's plan", { exact: true })).toBeVisible();
  await expect(review.getByRole("checkbox")).toHaveCount(1);
  await review.getByRole("checkbox", { name: unfinished.content, exact: true }).check();
  const carry = review.getByRole("button", { name: "Add selected goals to this week", exact: true });
  await carry.click();
  await expect(review.getByText("Selected goals added to this week's plan.", { exact: true })).toBeVisible();
  await expect(plan.getByText("0 of 3 planned goals complete", { exact: true })).toBeVisible();
  await expect(review.getByRole("checkbox")).toHaveCount(0);
  const pastAfter = await a.client.from("weekly_focus_plans").select("task_ids,version").eq("week_start", lastWeek).single();
  requireSuccess(pastAfter.error, "Read untouched prior plan");
  expect(pastAfter.data).toEqual({ task_ids: oldIds, version: old.data![0].version });
  const tasksAfter = await a.client.from("tasks").select("id,content,is_done,room_code,is_shared").order("id");
  requireSuccess(tasksAfter.error, "Read unchanged review source goals"); expect(tasksAfter.data).toEqual(taskSnapshot.data);
  const denied = await b.client.from("weekly_focus_plans").select("*").eq("user_id", a.id);
  requireSuccess(denied.error, "Read review privacy boundary"); expect(denied.data).toEqual([]);
  await b.page.getByRole("button", { name: "Review last week", exact: true }).click();
  await expect(b.page.getByRole("region", { name: "Private weekly plan review" })).toContainText("No goals saved in last week's plan.");
  await expect(b.page.getByText(unfinished.content, { exact: true })).toHaveCount(0);
  await a.page.bringToFront();
  await plan.getByRole("button", { name: `Remove ${unfinished.content} from weekly plan`, exact: true }).click();
  await expect(review.getByRole("checkbox", { name: unfinished.content, exact: true })).toBeEnabled();
  await review.getByRole("checkbox", { name: unfinished.content, exact: true }).check();
  const beforeConflict = await a.client.from("weekly_focus_plans").select("version").eq("week_start", week).single();
  requireSuccess(beforeConflict.error, "Read current review revision");
  requireSuccess((await a.client.rpc("set_weekly_focus_plan", { p_week_start: week, p_task_ids: [already.id], p_expected_version: beforeConflict.data!.version })).error, "Change plan from a second device");
  await carry.click();
  await expect(plan.getByText(/Your plan changed elsewhere/)).toBeVisible();
  await plan.getByRole("button", { name: "Reload plan", exact: true }).click();
  await expect(review.getByRole("checkbox", { name: unfinished.content, exact: true })).not.toBeChecked();
  await review.getByRole("checkbox", { name: unfinished.content, exact: true }).check();
  const endpoint = "**/rest/v1/rpc/set_weekly_focus_plan";
  await a.page.route(endpoint, async route => {
    const response = await route.fetch(); expect(response.ok()).toBe(true);
    await route.fulfill({ status: 503, contentType: "application/json", body: '{"message":"Unavailable"}' });
  });
  await carry.click();
  await expect(plan.getByText(/Couldn't confirm this plan change/)).toBeVisible();
  await expect(review.getByText("Selected goals added to this week's plan.", { exact: true })).toHaveCount(0);
  await a.page.unroute(endpoint);
  await plan.getByRole("button", { name: "Reload plan", exact: true }).click();
  await expect(plan.getByText("0 of 2 planned goals complete", { exact: true })).toBeVisible();
  await expect(carry).toBeDisabled();
  // A goal completed elsewhere while selected must no longer be eligible.
  requireSuccess((await a.client.from("tasks").update({ is_done: false }).eq("id", finished.id).select("id").single()).error, "Reopen prior goal");
  await a.page.evaluate(() => window.dispatchEvent(new Event("focus")));
  await review.getByRole("checkbox", { name: finished.content, exact: true }).check();
  requireSuccess((await a.client.from("tasks").update({ is_done: true }).eq("id", finished.id).select("id").single()).error, "Complete selected prior goal");
  await a.page.evaluate(() => window.dispatchEvent(new Event("focus")));
  await expect(review.getByRole("checkbox", { name: finished.content, exact: true })).toHaveCount(0);
  await expect(carry).toBeDisabled();
  expect((await new AxeBuilder({ page: a.page }).include('[aria-label="Private weekly plan review"]').withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  for (const [name, width, height] of [["phone", 375, 667], ["landscape", 667, 375]] as const) {
    await a.page.setViewportSize({ width, height }); await carry.scrollIntoViewIfNeeded();
    expect(await carry.evaluate(element => element.getBoundingClientRect().height)).toBeGreaterThanOrEqual(44);
    expect(await a.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await a.page.screenshot({ path: test.info().outputPath(`weekly-review-${name}.png`) });
  }
  await a.page.reload(); await expect(review).toHaveCount(0);
  await plan.getByRole("button", { name: "Review last week", exact: true }).click();
  await expect(review.getByText("Already in this week's plan", { exact: true })).toHaveCount(2);
});
